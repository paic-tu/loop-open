-- =====================================================================
-- تحديث أرقام الأثر (cms_impact_stats) في الصفحة الرئيسية
--   البطاقة الثانية: القيمة الجديدة «20 مليون ريال دعم محصل» + وصف التحصيل
--   البطاقة الثالثة: القيمة «+200» بدل «+300» + وصف الحملات الجديد
-- تنفيذ آمن ومتكرر (Idempotent) — لا يُنشئ صفوفاً جديدة.
-- =====================================================================

UPDATE public.cms_impact_stats
SET stat_value  = '20 مليون ريال دعم محصل',
    description = 'تحصيل دعم أكثر من عشرين مليون ريال لصالح القطاع غير الربحي',
    updated_at  = NOW()
WHERE title = 'تنمية واسترداد';

UPDATE public.cms_impact_stats
SET stat_value  = '+200',
    description = 'إدارة وتنفيذ أكثر من 200 حملة تسويقية تستهدف تعميق الأثر المجتمعي وصناعة التفاعل الرقمي',
    updated_at  = NOW()
WHERE title = 'حملة تسويقية';
